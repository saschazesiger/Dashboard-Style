/**
 * The AI label (3.0): its height at every size and density, the shape,
 * the touch target, the toggletip (aria-expanded, the focus in and back,
 * Escape, a press outside, Tab away, placement under the label), names and
 * forced colours. Runs in the `fallback` project too.
 */
import { test, expect } from '../../../test/browser/base-test.js';
import { ready, settle } from '../../../test/browser/helpers/motion.js';

async function open(page) {
  await page.goto('/test/browser/fixtures/component.html?c=ailabel');
  await ready(page);
  await page.mouse.move(1, 1);
}

const toggle = (page) => page.locator('button.ds-ailabel').first();
const tipOf = async (page) => page.locator(`#${await toggle(page).getAttribute('aria-controls')}`);

test('the height steps 4px per size and 2px per density; the shape squares it', async ({ page }) => {
  await open(page);
  const measured = await page.evaluate(() => {
    const region = document.createElement('div');
    document.querySelector('#fx-component').append(region);
    const at = (classes) => {
      region.className = classes;
      region.innerHTML = '<span class="ds-ailabel">AI</span>';
      const el = region.querySelector('.ds-ailabel');
      return { height: el.getBoundingClientRect().height, radius: parseFloat(getComputedStyle(el).borderTopLeftRadius) };
    };
    const out = { xs: at('ds-xs'), sm: at('ds-sm'), md: at(''), lg: at('ds-lg'), xl: at('ds-xl'), dense: at('ds-density-dense'), tight: at('ds-xs ds-density-tight'), square: at('ds-shape-square') };
    region.remove();
    return out;
  });
  expect([measured.xs.height, measured.sm.height, measured.md.height, measured.lg.height, measured.xl.height]).toEqual([16, 20, 24, 28, 32]);
  expect(measured.dense.height).toBe(20);
  expect(measured.tight.height).toBe(16);
  expect(measured.md.radius).toBe(12);
  expect(measured.square.radius).toBe(0);
});

test('under .ds-touch the button keeps its size and its target reaches 48px', async ({ page }) => {
  await open(page);
  const target = await toggle(page).evaluate((el) => {
    el.parentElement.classList.add('ds-touch');
    const after = getComputedStyle(el, '::after');
    const box = el.getBoundingClientRect();
    return { height: box.height, target: box.height - 2 * parseFloat(after.top) };
  });
  expect(target.height).toBe(24);
  expect(target.target).toBeGreaterThanOrEqual(48);
});

test('a press opens the explainer under the label with the focus in it; Escape closes it and the focus returns', async ({ page }) => {
  await open(page);
  const tip = await tipOf(page);
  await expect(toggle(page)).toHaveAttribute('aria-expanded', 'false');
  await toggle(page).click();
  await expect(tip).toHaveAttribute('data-state', 'open');
  await expect(toggle(page)).toHaveAttribute('aria-expanded', 'true');
  await expect(tip).toBeFocused();
  await expect(page.getByRole('dialog', { name: 'Generated by AI' }).first()).toBeVisible();
  // Measured at rest: it grows from the label on the spring.
  await settle(page);
  const label = await toggle(page).boundingBox();
  const box = await tip.boundingBox();
  expect(box.y).toBeGreaterThanOrEqual(label.y + label.height);
  expect(Math.abs(box.x - label.x)).toBeLessThanOrEqual(1);
  await page.keyboard.press('Escape');
  await expect(tip).toBeHidden();
  await expect(toggle(page)).toBeFocused();
  await expect(toggle(page)).toHaveAttribute('aria-expanded', 'false');
});

test('create() returns the controller the attribute path made, once per element', async ({ page }) => {
  await open(page);
  const same = await toggle(page).evaluate((button) => {
    const made = DS.ailabel.create(button);
    return { path: made === DS.core.get(button, 'ailabel'), again: made === DS.ailabel.create(button) };
  });
  expect(same).toEqual({ path: true, again: true });
});

test('a second press, a press outside or a focus that leaves closes it', async ({ page }) => {
  await open(page);
  const tip = await tipOf(page);
  await toggle(page).click();
  await expect(tip).toHaveAttribute('data-state', 'open');
  await toggle(page).click();
  await expect(tip).toBeHidden();
  await toggle(page).click();
  await expect(tip).toHaveAttribute('data-state', 'open');
  await page.mouse.click(5, 5);
  await expect(tip).toBeHidden();
  await toggle(page).press('Enter');
  await expect(tip).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(tip.getByRole('link')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(tip).toBeHidden();
  expect(await page.evaluate(() => DS.ailabel.create(document.querySelector('button.ds-ailabel')).get())).toEqual({ open: false });
});

test('names: a static label is read as text, the icon alone by its name, the button says what it opens', async ({ page }) => {
  await open(page);
  await expect(page.locator('span.ds-ailabel').first()).toHaveText('AI generated');
  await expect(page.getByRole('img', { name: 'AI generated' })).toHaveCount(1);
  await expect(toggle(page)).toHaveAccessibleName(/^AI ?: about this content$/);
  await expect(page.locator('button.ds-ailabel--icon')).toHaveAccessibleName('AI generated: about this content');
});

test('forced colours: the label keeps its edge, the open button is Highlight', async ({ page, browserName }) => {
  test.skip(browserName !== 'chromium', 'forced colours are emulated in Chromium only');
  await page.emulateMedia({ forcedColors: 'active' });
  await open(page);
  await toggle(page).click();
  const colours = await toggle(page).evaluate((el) => {
    const probe = document.createElement('span');
    probe.style.color = 'Highlight';
    document.body.append(probe);
    const highlight = getComputedStyle(probe).color;
    probe.remove();
    return { background: getComputedStyle(el).backgroundColor, highlight, edge: getComputedStyle(document.querySelector('span.ds-ailabel')).borderTopColor };
  });
  expect(colours.background).toBe(colours.highlight);
  expect(colours.edge).not.toBe('rgba(0, 0, 0, 0)');
});
