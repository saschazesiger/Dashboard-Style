/**
 * Static server for the browser tests: the repository root on
 * http://127.0.0.1:4173 (or the port given, else DS_TEST_PORT), so fixtures
 * load /dist/... exactly as a project would and the styleguide runs at
 * /styleguide/index.html.
 *
 *   node test/browser/serve.js [port]
 *
 * Dependency-free (node:http). Correct MIME types (module fixtures need
 * text/javascript), nothing outside the root, no directory listings and no
 * caching headers, so every run sees the files as they are on disk.
 *
 * One generated route: /test/browser/fixtures/component.html?c=<name>
 * renders the demo of src/components/<name>/<name>.demo.js alone
 * (componentFixture()): dist/ loaded as a project loads it, the styleguide's
 * own demo API (styleguide/sg-core.js, so a demo gets the same helpers as on
 * its styleguide page), the demo file, every registered demo mounted through
 * SG.mount() (or only `demo=<demo name>`), then DS.init(document) and
 * DS.ripple.attach(document); fixture.js marks data-fixture-ready. `min=1`
 * loads ds.min.css and ds.min.js instead.
 */
import { createServer } from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import { dirname, extname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const PORT = Number(process.argv[2] || process.env.DS_TEST_PORT || 4173);
const HOST = '127.0.0.1';

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/plain; charset=utf-8',
};

/** The path of the generated per-component fixture page. */
export const COMPONENT_FIXTURE = '/test/browser/fixtures/component.html';

/** A component folder name (src/components/<name>/). */
const COMPONENT_NAME = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

/**
 * The fixture page of one component (see the file comment), or null when
 * `c` is no component name. The names go into the page as JSON, so a
 * query string can never inject markup.
 */
export function componentFixture(params) {
  const name = params.get('c') || '';
  if (!COMPONENT_NAME.test(name)) return null;
  const only = params.get('demo') || '';
  const min = params.get('min') === '1' ? '.min' : '';
  const demo = `/src/components/${name}/${name}.demo.js`;
  return `<!doctype html>
<html lang="en" class="ds-base">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${name} · component fixture</title>
<link rel="stylesheet" href="/dist/fonts/fonts.css">
<link rel="stylesheet" href="/dist/ds${min}.css">
<link rel="stylesheet" href="/test/browser/fixtures/fixture.css">
<link rel="stylesheet" href="/styleguide/shell.css">
</head>
<body class="ds-theme">
<!-- Generated by test/browser/serve.js: the demo of ${demo} alone. -->
<main class="fx-root" id="fx-component" data-component=${JSON.stringify(name).replace(/</g, '\\u003c')}></main>
<script src="/dist/ds${min}.js"></script>
<script src="/styleguide/sg-core.js"></script>
<script src="${demo}"></script>
<script>
  (function () {
    var only = ${JSON.stringify(only).replace(/</g, '\\u003c')};
    var main = document.getElementById('fx-component');
    var chosen = SG.list().filter(function (spec) { return !only || spec.name === only; });
    if (!chosen.length) throw new Error('component.html: no demo' + (only ? ' named ' + only : '') + ' registered');
    chosen.forEach(function (spec) { SG.mount(spec.name, main.appendChild(document.createElement('div'))); });
    window.componentFixture = { name: ${JSON.stringify(name)}, mounted: chosen.length };
  })();
  DS.init(document);
  DS.ripple.attach(document);
</script>
<script src="/test/browser/fixtures/fixture.js"></script>
</body>
</html>
`;
}

function send(response, status, body, type = 'text/plain; charset=utf-8') {
  response.writeHead(status, { 'Content-Type': type, 'Content-Length': Buffer.byteLength(body) });
  response.end(body);
}

/** The file a request path names, or null when it would leave the root. */
function resolvePath(url) {
  let pathname;
  try {
    pathname = decodeURIComponent(new URL(url, `http://${HOST}`).pathname);
  } catch {
    return null;
  }
  if (pathname.includes('\0')) return null;
  const path = resolve(ROOT, `.${pathname}`);
  return path === ROOT || path.startsWith(ROOT + sep) ? path : null;
}

export function createStaticServer() {
  return createServer(async (request, response) => {
    if (request.method !== 'GET' && request.method !== 'HEAD') return send(response, 405, 'Method not allowed');
    const url = new URL(request.url, `http://${HOST}`);
    if (url.pathname === COMPONENT_FIXTURE) {
      const page = componentFixture(url.searchParams);
      if (!page) return send(response, 404, 'Not found: component.html?c=<component name>');
      return send(response, 200, request.method === 'HEAD' ? '' : page, TYPES['.html']);
    }
    const path = resolvePath(request.url);
    if (!path) return send(response, 403, 'Forbidden');
    try {
      // Directories get no listing and no index file: tests name the page.
      if (!(await stat(path)).isFile()) return send(response, 404, 'Not found');
      const body = await readFile(path);
      response.writeHead(200, {
        'Content-Type': TYPES[extname(path).toLowerCase()] || 'application/octet-stream',
        'Content-Length': body.length,
      });
      response.end(request.method === 'HEAD' ? undefined : body);
    } catch {
      send(response, 404, 'Not found');
    }
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  createStaticServer().listen(PORT, HOST, () => {
    process.stdout.write(`Serving ${ROOT} on http://${HOST}:${PORT}/\n`);
  });
}
